def shown_frame(df: pd.DataFrame, show_all: bool, limit: int = 200) -> tuple[pd.DataFrame, int, int]:
    total = 0 if df is None else len(df)
    if df is None or df.empty:
        return df if df is not None else pd.DataFrame(), 0, 0
    if show_all:
        return df, total, total
    part = df.head(limit)
    return part, len(part), total
